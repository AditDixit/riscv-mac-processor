#!/usr/bin/env python3
"""Run the official RISC-V architectural tests (riscv-arch-test 2.7.4) on the RTL.

Usage: run_arch.py <build-dir>

Fetches riscv-arch-test release 2.7.4 (the last release that ships reference
signatures, generated by the Sail formal model of the ISA), compiles every
RV32I test plus mul-01 from the M suite with riscv64-unknown-elf-gcc, runs each
on the pipeline in Verilator, and compares the signature region word for word
with the reference. Requires git, the RISC-V GCC cross toolchain and Verilator.

Two notes on how the tests are built:
  * The image is linked at address 0 and loaded into both instruction and data
    memory (the core has separate memories; tests read data PC-relatively).
  * jalr-01 contains `la x0, <label>`, which newer assemblers reject. Writing
    x0 has no effect, so it is replaced by two nops (the same size as the la
    pair), leaving every other instruction at the same address.
"""
import os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RTL = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.dirname(HERE))
import simrun  # noqa: E402  (for the RTL source list)

TAG = "2.7.4"
GCC = "riscv64-unknown-elf-"
CFLAGS = ["-march=rv32im", "-mabi=ilp32", "-static", "-mcmodel=medany", "-fvisibility=hidden",
          "-nostdlib", "-nostartfiles", "-DXLEN=32", "-DTEST_CASE_1=True"]


def sh(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw)


def fetch(work):
    act = os.path.join(work, "riscv-arch-test")
    if not os.path.isdir(act):
        sh(["git", "clone", "-q", "--depth", "1", "--branch", TAG,
            "https://github.com/riscv-non-isa/riscv-arch-test", act])
    return os.path.join(act, "riscv-test-suite")


def build_tb(work):
    cmd = ["verilator", "--binary", "--timing", "-Wno-fatal", "-Wno-lint", "-Wno-style",
           "--top-module", "tb_arch", "-Mdir", os.path.join(work, "obj"),
           "-CFLAGS", "-std=c++20 -fcoroutines", os.path.join(HERE, "tb_arch.v")] + \
          [os.path.join(RTL, s) for s in simrun.SRCS]
    sh(cmd)
    return os.path.join(work, "obj", "Vtb_arch")


def compile_test(src, suite, work):
    name = os.path.basename(src)[:-2]
    inc = ["-I", os.path.join(suite, "env"), "-I", HERE]
    pre = sh([GCC + "gcc", "-E", *CFLAGS, *inc, src]).stdout
    pre = re.sub(r"\bla x0,[^;\n]*", "nop;nop", pre)
    s_file = os.path.join(work, name + ".s")
    open(s_file, "w").write(pre)
    elf = os.path.join(work, name + ".elf")
    sh([GCC + "gcc", *CFLAGS, "-T", os.path.join(HERE, "link.ld"), s_file, "-o", elf])
    syms = {}
    for line in sh([GCC + "nm", elf]).stdout.splitlines():
        p = line.split()
        if len(p) == 3:
            syms[p[2]] = int(p[0], 16)
    binf = os.path.join(work, name + ".bin")
    sh([GCC + "objcopy", "-O", "binary", elf, binf])
    data = open(binf, "rb").read()
    data += b"\0" * (-len(data) % 4)
    hexf = os.path.join(work, name + ".hex")
    with open(hexf, "w") as f:
        for i in range(0, len(data), 4):
            f.write(f"{int.from_bytes(data[i:i + 4], 'little'):08x}\n")
    return hexf, syms


def main():
    work = os.path.abspath(sys.argv[1])
    os.makedirs(work, exist_ok=True)
    suite = fetch(work)
    exe = build_tb(work)
    tests = []
    for sub, names in (("I", None), ("M", ["mul-01"])):
        d = os.path.join(suite, "rv32i_m", sub)
        for f in sorted(os.listdir(os.path.join(d, "src"))):
            n = f[:-2]
            if f.endswith(".S") and (names is None or n in names):
                tests.append((sub, n, os.path.join(d, "src", f),
                              os.path.join(d, "references", n + ".reference_output")))
    passed, rows = 0, []
    for sub, n, src, ref in tests:
        hexf, syms = compile_test(src, suite, work)
        out = os.path.join(work, n + ".signature")
        r = sh([exe, f"+PROG={hexf}", f"+HALT={syms['rvmodel_halt']}",
                f"+SIGB={syms['begin_signature']}", f"+SIGE={syms['end_signature']}", f"+OUT={out}"])
        cyc = re.search(r"CYCLES (\d+)", r.stdout).group(1)
        got = open(out).read().split()
        exp = open(ref).read().split()
        bad = sum(g != e for g, e in zip(got, exp)) + abs(len(got) - len(exp))
        ok = bad == 0 and "TIMEOUT" not in r.stdout
        passed += ok
        rows.append((f"{sub}/{n}", len(exp), bad, cyc, ok))
        print(f"{'PASS' if ok else 'FAIL'}  {sub}/{n:<14} signature words={len(exp):<5} "
              f"mismatches={bad:<4} cycles={cyc}", flush=True)
    words = sum(r[1] for r in rows)
    print(f"ARCH-TEST passed={passed}/{len(tests)} signature_words={words}")
    sys.exit(0 if passed == len(tests) else 1)


if __name__ == "__main__":
    main()
